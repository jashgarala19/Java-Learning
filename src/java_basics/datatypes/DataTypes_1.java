package java_basics.datatypes;

public class DataTypes_1 {

    public static void main(String[] args) {

        /// Primitive Types
        // whole numbers
        byte bb = 45; // stores between -128 to 127
        short sh = 345;  // stores between -32768 to 32767
        int a = 10; // integer
        long l = 142555;

        // fractional
        float f = 10.5f; //float
        double d = 10.5d; // double

        char c = 'c'; //character


        // String
        String s = "Hello Jash"; //string

        boolean b = true; //boolean





    }
}
